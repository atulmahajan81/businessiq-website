"""Generate learn/glossary.html from content/glossary.json.

The visible markup and the DefinedTermSet JSON-LD are emitted from the same
source, so they cannot drift apart. Run after editing the JSON:

    python tools/build-glossary.py

Output is committed; the deployed site stays static with no build step.
"""
import html
import io
import json
import pathlib
from collections import OrderedDict

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "content" / "glossary.json"
OUT = ROOT / "learn" / "glossary.html"

SITE = "https://www.businessiq.co.in"
URL = SITE + "/learn/glossary"

TITLE = "Franchise Glossary — 51 Terms Explained | BusinessIQ"
DESC = ("Plain-English definitions of the franchise terms Indian investors meet in "
        "contracts and cost sheets — royalty, FDD, master franchise, unit economics and more.")


def esc(s):
    return html.escape(s, quote=False)


def nav():
    items = [("/#about", "About"), ("/brands", "Brands"), ("/#why-us", "Why Us"),
             ("/#investment", "Investment"), ("/learn", "Learn"),
             ("/#faq", "FAQ"), ("/#contact", "Contact")]
    lis = "\n".join(
        '        <li><a href="%s">%s</a></li>' % (href, label) for href, label in items)
    return lis


def build():
    data = json.loads(SRC.read_text(encoding="utf-8"))
    terms = sorted(data["terms"], key=lambda t: t["term"].lower())
    by_slug = {t["slug"]: t["term"] for t in terms}

    groups = OrderedDict()
    for t in terms:
        groups.setdefault(t["term"][0].upper(), []).append(t)

    # A-Z jump bar: every letter rendered, unused ones dimmed and unlinked.
    jump = []
    for ch in "ABCDEFGHIJKLMNOPQRSTUVWXYZ":
        if ch in groups:
            jump.append('<a href="#letter-%s">%s</a>' % (ch, ch))
        else:
            jump.append('<span aria-hidden="true">%s</span>' % ch)
    jump_bar = "\n        ".join(jump)

    sections = []
    for letter, items in groups.items():
        rows = []
        for t in items:
            also = ""
            if t.get("seeAlso"):
                links = ", ".join(
                    '<a href="#%s">%s</a>' % (s, esc(by_slug[s]))
                    for s in t["seeAlso"] if s in by_slug)
                if links:
                    also = '\n            <p class="g-also">See also: %s</p>' % links
            rows.append(
                '          <div class="g-term" id="%s">\n'
                '            <h3>%s <span class="g-cat">%s</span></h3>\n'
                '            <p>%s</p>%s\n'
                '          </div>'
                % (t["slug"], esc(t["term"]), esc(t["category"]), esc(t["definition"]), also))
        sections.append(
            '        <section class="g-group" aria-labelledby="letter-%s">\n'
            '          <h2 class="g-letter" id="letter-%s">%s</h2>\n%s\n'
            '        </section>' % (letter, letter, letter, "\n".join(rows)))

    defined_terms = [{
        "@type": "DefinedTerm",
        "@id": "%s#%s" % (URL, t["slug"]),
        "name": t["term"],
        "description": t["definition"],
        "inDefinedTermSet": URL,
    } for t in terms]

    term_set = {
        "@context": "https://schema.org",
        "@type": "DefinedTermSet",
        "@id": URL,
        "name": data["title"],
        "description": DESC,
        "url": URL,
        "hasDefinedTerm": defined_terms,
    }

    crumbs = {
        "@context": "https://schema.org",
        "@type": "BreadcrumbList",
        "itemListElement": [
            {"@type": "ListItem", "position": 1, "name": "Home", "item": SITE + "/"},
            {"@type": "ListItem", "position": 2, "name": "Learn", "item": SITE + "/learn"},
            {"@type": "ListItem", "position": 3, "name": "Franchise Glossary", "item": URL},
        ],
    }

    def ld(obj):
        return json.dumps(obj, indent=2, ensure_ascii=False)

    page = """<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1.0" />
  <!-- GENERATED by tools/build-glossary.py from content/glossary.json. Do not edit by hand. -->
  <title>%(title)s</title>
  <meta name="description" content="%(desc)s" />
  <meta name="author" content="BusinessIQ.co.in" />
  <meta name="robots" content="index, follow, max-snippet:-1, max-image-preview:large" />
  <link rel="icon" type="image/svg+xml" href="/assets/favicon.svg" />
  <link rel="canonical" href="%(url)s" />

  <meta property="og:title" content="Franchise Glossary — 51 Terms Explained" />
  <meta property="og:description" content="%(desc)s" />
  <meta property="og:type" content="article" />
  <meta property="og:url" content="%(url)s" />
  <meta property="og:image" content="%(site)s/assets/og-image.png" />
  <meta property="og:image:width" content="1200" />
  <meta property="og:image:height" content="630" />
  <meta property="og:image:type" content="image/png" />
  <meta property="og:image:alt" content="BusinessIQ franchise glossary" />
  <meta property="og:locale" content="en_IN" />
  <meta property="og:site_name" content="BusinessIQ" />
  <meta name="twitter:card" content="summary_large_image" />
  <meta name="twitter:title" content="Franchise Glossary — 51 Terms Explained" />
  <meta name="twitter:description" content="%(desc)s" />
  <meta name="twitter:image" content="%(site)s/assets/og-image.png" />

  <link rel="preconnect" href="https://fonts.googleapis.com" />
  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin />
  <link href="https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600;700;800;900&display=swap" rel="stylesheet" />
  <link rel="stylesheet" href="/css/style.css" />

  <script type="application/ld+json">
%(termset)s
  </script>
  <script type="application/ld+json">
%(crumbs)s
  </script>

  <style>
    .g-jump {
      position: sticky; top: 104px; z-index: 50;
      background: #fff; border-bottom: 1px solid var(--border);
      padding: 0.6rem 0; display: flex; flex-wrap: wrap; gap: 0.15rem;
      justify-content: center; font-size: 0.82rem; font-weight: 700;
    }
    .g-jump a, .g-jump span {
      min-width: 1.6rem; text-align: center; padding: 0.2rem 0.1rem; border-radius: 5px;
    }
    .g-jump a { color: var(--primary); }
    .g-jump a:hover { background: var(--bg-light); color: var(--accent-dark); }
    .g-jump span { color: var(--border); }

    .g-group { margin-bottom: 2.5rem; }
    .g-letter {
      font-size: 1.5rem; color: var(--accent); border-bottom: 2px solid var(--border);
      padding-bottom: 0.4rem; margin-bottom: 1.25rem;
    }
    .g-term { padding: 1.1rem 0; border-bottom: 1px solid var(--border); scroll-margin-top: 160px; }
    .g-term:last-child { border-bottom: none; }
    .g-term h3 {
      font-size: 1.05rem; color: var(--primary); margin: 0 0 0.4rem;
      display: flex; align-items: center; gap: 0.6rem; flex-wrap: wrap;
    }
    .g-cat {
      font-size: 0.66rem; font-weight: 700; text-transform: uppercase; letter-spacing: 0.05em;
      background: var(--bg-light); color: var(--text-muted);
      padding: 0.2rem 0.6rem; border-radius: 999px; border: 1px solid var(--border);
    }
    .g-term p { color: var(--text-muted); line-height: 1.75; margin: 0; font-size: 0.94rem; }
    .g-also { margin-top: 0.5rem !important; font-size: 0.84rem !important; }
    .g-also a { color: var(--primary); font-weight: 600; text-decoration: underline; }
    .g-also a:hover { color: var(--accent-dark); }

    @media (max-width: 600px) {
      .g-jump { top: 92px; font-size: 0.76rem; }
      .g-term { scroll-margin-top: 150px; }
    }
  </style>
</head>
<body>

<div class="ifc-bar">
  <span class="ifc-long">BusinessIQ is an <strong style="color:#e8a020;">Authorized Independent Franchise Consultant (IFC)</strong> of <strong style="color:#fff;">Franchise India Consultants Pvt. Ltd.</strong> &nbsp;|&nbsp; All leads &amp; enquiries are processed through Franchise India.</span>
  <span class="ifc-short"><strong style="color:#e8a020;">Authorized IFC</strong> &middot; Franchise India Consultants Pvt. Ltd.</span>
</div>

<nav class="navbar" id="navbar" role="navigation" aria-label="Main navigation">
  <div class="container">
    <div class="nav-inner">
      <a href="/" class="nav-logo" aria-label="BusinessIQ home">
        <img src="/assets/logo-icon.svg" alt="" height="36" width="36" aria-hidden="true" />
        Business<span>IQ</span>
      </a>
      <ul class="nav-links" id="navLinks">
%(nav)s
      </ul>
      <a href="/#contact" class="btn btn-primary nav-cta">Get Started &rarr;</a>
      <button class="hamburger" id="hamburger" aria-label="Toggle menu" aria-expanded="false">
        <span></span><span></span><span></span>
      </button>
    </div>
  </div>
</nav>

<header class="page-hero">
  <div class="container">
    <span class="tag">&#128218; Learn</span>
    <h1>Franchise <span>Glossary</span></h1>
    <p>%(intro)s</p>
  </div>
</header>

<nav class="breadcrumb" aria-label="Breadcrumb">
  <div class="container">
    <a href="/">Home</a> <span>&rsaquo;</span> <a href="/learn">Learn</a> <span>&rsaquo;</span> <span>Glossary</span>
  </div>
</nav>

<nav class="g-jump" aria-label="Jump to letter">
  <div class="container" style="display:flex;flex-wrap:wrap;gap:0.15rem;justify-content:center;">
        %(jump)s
  </div>
</nav>

<main class="page-body">
  <div class="container">
    <div class="prose">
%(sections)s
    </div>

    <div class="page-cta">
      <h2>Still working out which franchise fits?</h2>
      <p>Knowing the terms is the start. Tell us your budget and city and we will shortlist brands that genuinely match.</p>
      <a href="/#contact" class="btn btn-primary">Book Free Consultation &rarr;</a>
      <a href="/brands" class="btn btn-outline">Browse Brands</a>
    </div>
  </div>
</main>

<footer role="contentinfo">
  <div class="container">
    <div class="footer-bottom" style="border-top:none;padding-top:0;">
      <p>&copy; 2026 BusinessIQ.co.in. All Rights Reserved. &nbsp;|&nbsp; Authorized IFC of <strong>Franchise India Consultants Pvt. Ltd.</strong></p>
      <nav class="footer-legal" aria-label="Legal links">
        <a href="/privacy">Privacy Policy</a>
        <a href="/terms">Terms of Use</a>
        <a href="/disclaimer">Disclaimer</a>
      </nav>
    </div>
  </div>
</footer>

<button class="back-top" id="backTop" aria-label="Back to top">&uarr;</button>

<script>
  const navbar = document.getElementById('navbar');
  window.addEventListener('scroll', () => navbar.classList.toggle('scrolled', window.scrollY > 50));
  document.getElementById('hamburger').addEventListener('click', function () {
    const links = document.getElementById('navLinks');
    links.classList.toggle('open');
    this.setAttribute('aria-expanded', links.classList.contains('open'));
  });
  const backTop = document.getElementById('backTop');
  window.addEventListener('scroll', () => backTop.classList.toggle('visible', window.scrollY > 400));
  backTop.addEventListener('click', () => window.scrollTo({ top: 0, behavior: 'smooth' }));
</script>
<script src="/js/analytics.js"></script>
</body>
</html>
""" % {
        "title": esc(TITLE),
        "desc": esc(DESC),
        "url": URL,
        "site": SITE,
        "nav": nav(),
        "intro": esc(data["intro"]),
        "jump": jump_bar,
        "sections": "\n".join(sections),
        "termset": ld(term_set),
        "crumbs": ld(crumbs),
    }

    OUT.parent.mkdir(parents=True, exist_ok=True)
    with io.open(str(OUT), "w", encoding="utf-8", newline="\n") as fh:
        fh.write(page)
    print("wrote %s (%d terms, %d letters)" % (OUT.relative_to(ROOT), len(terms), len(groups)))


if __name__ == "__main__":
    build()
